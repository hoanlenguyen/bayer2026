"""Action tracker: turns findings into accountable follow-up work.

- Proposals are generated by plain Python from the decision and the catalog.
  Nothing becomes an action until a person accepts it and names an owner.
- Two kinds stay separate: ``business`` (act on what the analytics show) and
  ``maintenance`` (fix the analytics themselves: owners, duplicates, refresh, tests).
- Completing the work (``done``) is recorded separately from verifying that the
  measured outcome improved (``verified`` with a result).
"""
from __future__ import annotations

import uuid
from datetime import date, datetime, timedelta, timezone
from typing import Any

from . import catalog as cat

STATUSES = ("open", "in_progress", "blocked", "done", "verified", "dismissed")
CLOSED = {"verified", "dismissed"}
TRANSITIONS: dict[str, set[str]] = {
    "open": {"in_progress", "blocked", "done", "dismissed"},
    "in_progress": {"open", "blocked", "done", "dismissed"},
    "blocked": {"in_progress", "done", "dismissed"},
    "done": {"verified", "in_progress"},
    "verified": set(),
    "dismissed": {"open"},
}


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def verify_target(measure_id: str) -> dict[str, Any]:
    m = cat.CATALOG["measures"].get(measure_id, {})
    lower = bool(m.get("lower_is_better"))
    return {"metric_id": measure_id, "metric_name": m.get("name", measure_id),
            "direction": "decrease" if lower else "increase", "result": None, "note": "", "checked_at": None, "checked_by": None}


# ---------------------------------------------------------------- proposals
def propose(intent: dict[str, Any], decision: dict[str, Any], existing: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Follow-up actions suggested by this request. Deterministic; a person decides which to accept."""
    C = cat.CATALOG
    out: list[dict[str, Any]] = []
    cand = decision.get("candidate") or {}
    dec = decision["decision"]

    def add(key: str, kind: str, title: str, reason: str, owner: str, due_in_days: int,
            asset_id: str | None = None, verify: dict[str, Any] | None = None) -> None:
        if any(p["key"] == key for p in out):
            return
        open_match = next((a for a in existing if a.get("key") == key and a.get("status") not in CLOSED), None)
        out.append({"key": key, "kind": kind, "title": title, "reason": reason, "owner": owner,
                    "due_date": (date.today() + timedelta(days=due_in_days)).isoformat(), "asset_id": asset_id,
                    "asset_name": (cat.asset_by_id(asset_id) or {}).get("name") if asset_id else None,
                    "verify": verify, "existing_action_id": open_match["_id"] if open_match else None})

    def steward(asset: dict[str, Any] | None) -> str:
        return asset["owner"] if asset and asset.get("owner_status") == "active" else "Data steward"

    # Business: act on the decision the request supports, then check the number moved.
    if dec != "not_feasible" and intent.get("measures"):
        m0 = next((m for m in intent["measures"] if C["measures"].get(m, {}).get("fact_column")), intent["measures"][0])
        target = verify_target(m0)
        add(f"biz:{intent.get('preset_id') or '-'}:{intent['decision']}", "business", intent["decision"].rstrip(". "),
            f"From your request. Afterwards, {target['metric_name']} should {'go down' if target['direction'] == 'decrease' else 'go up'}.",
            "You (requester)", 30, cand.get("asset_id") if dec == "reuse" else None, target)

    # A dashboard built in Ask is reused before anyone owns it: the BI steward assigns an owner.
    saved = decision.get("saved_dashboard")
    if dec == "reuse" and saved and not saved.get("owner"):
        add(f"owner:{saved['id']}", "maintenance", f"Assign an owner to {saved['title']}",
            "This dashboard was built in Ask and is now being reused, but nobody answers for it yet (BI Portfolio: Needs an owner).",
            "BI steward", 14)

    # Maintenance: overlapping, legacy or poorly governed reports flagged by the decision.
    for f in decision.get("flags", []):
        a = cat.asset_by_id(f["asset_id"])
        if a and a.get("owner_status") != "active":
            add(f"maint:owner:{f['asset_id']}", "maintenance", f"Assign a new owner for {f['name']}",
                f"{a.get('owner')} is {a.get('owner_status')} (RULE-003).", "Data steward", 7, f["asset_id"])
        verb = "Retire" if "retire" in f["message"].lower() and "fold" not in f["message"].lower() else "Consolidate or retire"
        add(f"maint:retire:{f['asset_id']}", "maintenance", f"{verb} {f['name']}", f["message"], steward(a), 21, f["asset_id"])

    # Maintenance: data-quality issues on the model the decision builds on.
    model = cat.model_by_id(decision.get("target_model_id") or (cat.asset_by_id(cand.get("asset_id")) or {}).get("model_id"))
    if model and dec in ("new_build", "migrate", "consolidate"):
        for issue in model["dq_issues"]:
            if issue["severity"] in ("high", "medium"):
                add(f"maint:dq:{issue['id']}", "maintenance", f"Fix {issue['field'].replace('_', ' ')} on {model['name']} ({model['id']})",
                    f"{issue['value']}: {issue['impact']}", model.get("owner") or "Data steward", 14)

    # Maintenance: a governed KPI the shared model does not serve yet.
    gaps = (decision.get("availability") or {}).get("model_gaps") or []
    if dec == "new_build" and gaps and model:
        add(f"maint:modelgap:{model['id']}:{'|'.join(gaps)}", "maintenance",
            f"Add {', '.join(C['measures'][g]['name'] for g in gaps)} to {model['name']}",
            "The new report needs approved measures the shared model does not serve yet (RULE-001, RULE-002).",
            model.get("owner") or "Data steward", 14)

    if dec == "not_feasible":
        terms = (decision.get("availability") or {}).get("missing_terms") or intent.get("unmatched_terms") or []
        if not any("patient" in t or "prescriber" in t for t in terms):
            add(f"maint:source:{'|'.join(terms)}", "maintenance", f"Assess a governed source for: {', '.join(terms)}",
                "Requested but not in the catalog.", "Data platform team", 30)
    return out


# ---------------------------------------------------------------- create / update
def create(proposal: dict[str, Any], by: str, conversation_id: str | None = None, run_id: str | None = None,
           sample: bool = False) -> dict[str, Any]:
    title = str(proposal.get("title") or "").strip()
    if not title:
        raise ValueError("An action needs a title.")
    kind = proposal.get("kind", "business")
    if kind not in ("business", "maintenance"):
        raise ValueError("Kind must be 'business' or 'maintenance'.")
    owner = str(proposal.get("owner") or "").strip()
    if not owner:
        raise ValueError("An action needs an owner.")
    ts = now()
    return {
        "_id": "act_" + uuid.uuid4().hex[:10], "key": proposal.get("key"), "kind": kind, "title": title,
        "reason": proposal.get("reason", ""), "owner": owner, "due_date": proposal.get("due_date"),
        "status": "open", "asset_id": proposal.get("asset_id"), "asset_name": proposal.get("asset_name"),
        "conversation_id": conversation_id, "run_id": run_id, "blocker": "", "outcome": "",
        "verify": proposal.get("verify"), "created_at": ts, "updated_at": ts, "created_by": by, "sample": sample,
        "history": [{"at": ts, "by": by, "change": "created", "to": "open", "note": f"Assigned to {owner}"}],
    }


def apply_update(action: dict[str, Any], update: dict[str, Any], by: str) -> dict[str, Any]:
    """Validate and apply a change. Raises ValueError with a message for the user."""
    a = dict(action)
    history = list(a.get("history", []))
    ts = now()

    for field in ("owner", "due_date"):
        if field in update and update[field] is not None and update[field] != a.get(field):
            value = str(update[field]).strip()
            if field == "owner" and not value:
                raise ValueError("Owner cannot be empty.")
            if field == "due_date":
                date.fromisoformat(value)
            history.append({"at": ts, "by": by, "change": field, "from": a.get(field), "to": value})
            a[field] = value

    if update.get("blocker") is not None:
        a["blocker"] = str(update["blocker"]).strip()
    if update.get("outcome") is not None:
        a["outcome"] = str(update["outcome"]).strip()

    status = update.get("status")
    if status and status != a["status"]:
        if status not in STATUSES:
            raise ValueError(f"Unknown status '{status}'.")
        if status not in TRANSITIONS[a["status"]]:
            raise ValueError(f"Cannot move from {a['status'].replace('_', ' ')} to {status.replace('_', ' ')}.")
        if status == "blocked" and not a.get("blocker"):
            raise ValueError("Say what is blocking the action.")
        if status == "done" and not a.get("outcome"):
            raise ValueError("Describe what was done before marking it done.")
        if status == "verified":
            v = update.get("verification") or {}
            if v.get("result") not in ("improved", "not_improved", "confirmed"):
                raise ValueError("Record whether the outcome improved before verifying.")
            a["verify"] = {**(a.get("verify") or {}), "result": v["result"], "note": str(v.get("note", "")).strip(),
                           "checked_at": ts, "checked_by": by}
        result_text = {"improved": "Outcome improved", "not_improved": "Outcome did not improve", "confirmed": "Fix confirmed"}
        note = {"blocked": a.get("blocker"), "done": a.get("outcome"),
                "verified": result_text.get((a.get("verify") or {}).get("result"))}.get(status)
        history.append({"at": ts, "by": by, "change": "status", "from": a["status"], "to": status, "note": note})
        a["status"] = status

    a["history"] = history
    a["updated_at"] = ts
    return a


def is_overdue(action: dict[str, Any], today: date | None = None) -> bool:
    today = today or date.today()
    return bool(action.get("due_date")) and action["status"] in ("open", "in_progress", "blocked") \
        and date.fromisoformat(action["due_date"]) < today


def view(action: dict[str, Any]) -> dict[str, Any]:
    """Action as returned by the API: adds overdue and the statuses it may move to next."""
    return {**action, "overdue": is_overdue(action), "allowed": sorted(TRANSITIONS[action["status"]])}


def summary(actions: list[dict[str, Any]]) -> dict[str, int]:
    counts = {s: 0 for s in STATUSES}
    for a in actions:
        counts[a["status"]] += 1
    counts["overdue"] = sum(1 for a in actions if is_overdue(a))
    counts["awaiting_verification"] = counts["done"]
    counts["active"] = counts["open"] + counts["in_progress"] + counts["blocked"]
    return counts


# ---------------------------------------------------------------- sample actions
def sample_actions() -> list[dict[str, Any]]:
    """Example actions drawn from real signals in the data pack, so the tracker opens in a realistic state."""
    C = cat.CATALOG
    assets = sorted(C["assets"], key=lambda a: -a["views_90d"])
    no_owner = next(a for a in assets if a["owner_status"] != "active")
    failed = next(m for m in C["models"].values() if m["refresh_status"] == "failed" and m["assets"])
    legacy = next(a for a in assets if a["platform"] == "Tableau" and (a.get("migration") or {}).get("recommended_path_candidate") == "RETIRE")
    samples = [
        {"kind": "maintenance", "title": f"Assign a new owner for {no_owner['name']}", "owner": "Data steward",
         "reason": f"{no_owner['owner']} is {no_owner['owner_status']}; {no_owner['views_90d']:,} views in 90 days (RULE-003).",
         "asset_id": no_owner["id"], "due": 3, "status": "open", "key": f"maint:owner:{no_owner['id']}"},
        {"kind": "business", "title": "Review Nubeqa forecast variance in Germany with the country team", "owner": "Commercial Analytics Lead",
         "reason": "Forecast variance moved from -8.4% to +11.8% between September and October (synthetic).",
         "asset_id": None, "due": 5, "status": "in_progress", "verify": "forecast_variance"},
        {"kind": "maintenance", "title": f"Fix failing refresh of {failed['name']} ({failed['id']})", "owner": failed.get("owner") or "Data steward",
         "reason": f"Refresh failed; {len(failed['assets'])} reports depend on this model (RULE-004).", "asset_id": None, "due": -2,
         "status": "blocked", "blocker": "Waiting for the source system team to restore the gateway credentials.",
         "key": f"maint:refresh:{failed['id']}"},
        {"kind": "maintenance", "title": f"Retire {legacy['name']}", "owner": "BI Platform Owner",
         "reason": f"Tableau, backlog path RETIRE, {legacy['views_90d']:,} views in 90 days (RULE-006).", "asset_id": legacy["id"],
         "due": -1, "status": "done", "outcome": "Users redirected to the governed Power BI report; workbook archived.",
         "key": f"maint:retire:{legacy['id']}"},
    ]
    out = []
    for s in samples:
        a = create({"kind": s["kind"], "title": s["title"], "owner": s["owner"], "reason": s["reason"],
                    "asset_id": s["asset_id"], "asset_name": (cat.asset_by_id(s["asset_id"]) or {}).get("name") if s["asset_id"] else None,
                    "due_date": (date.today() + timedelta(days=s["due"])).isoformat(),
                    "verify": verify_target(s["verify"]) if s.get("verify") else None,
                    # Same keys as live proposals, so a proposal for the same finding links to the sample action.
                    "key": s.get("key", f"sample:{s['title']}")}, by="Sample data", sample=True)
        if s["status"] == "blocked":
            a = apply_update(a, {"blocker": s["blocker"], "status": "blocked"}, s["owner"])
        elif s["status"] == "done":
            a = apply_update(a, {"status": "in_progress"}, s["owner"])
            a = apply_update(a, {"outcome": s["outcome"], "status": "done"}, s["owner"])
        elif s["status"] != "open":
            a = apply_update(a, {"status": s["status"]}, s["owner"])
        out.append(a)
    return out
